-- 3. Create DISEASE_ANALYSIS Table (Skin Disease Analysis Patient Records CRUD)
CREATE TABLE DISEASE_ANALYSIS (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name VARCHAR2(100) NOT NULL,
    age NUMBER NOT NULL,
    symptom_redness VARCHAR2(10) CHECK (symptom_redness IN ('Yes', 'No')),
    symptom_itchy VARCHAR2(10) CHECK (symptom_itchy IN ('Yes', 'No')),
    symptom_scaling VARCHAR2(10) CHECK (symptom_scaling IN ('Yes', 'No')),
    duration NUMBER NOT NULL, -- duration in days
    diagnosis VARCHAR2(150) NOT NULL,
    notes VARCHAR2(1000)
);

